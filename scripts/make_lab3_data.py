#!/usr/bin/env python3
"""Generate the typed data modules of the Lab 3 experiment steps from the team's public repository.

Usage:   python3 scripts/make_lab3_data.py [path/to/transformers-nlp]
Default: /home/user/shashikanth077/transformers-nlp  (a read-only clone of github.com/shashikanth77/Transformers-NLP)

Reads   code/results/*.json, summary_table.csv, statistics.csv, subset_accuracy.csv, learning_curve.csv,
        code/*.py, code/run_all.sh, code/requirements.txt, study_guide/data.json (872 test sentences, TF-IDF + LR weights)
Writes  frontend/src/labs/lab3/data/exp*.ts   and   frontend/public/lab3/attention-fig7.png
Only the Python standard library is needed (the PNG is re-quantised if Pillow is installed). Nothing is typed by hand:
every number in the generated files comes from the repository, and the script asserts that the per-sentence predictions
of study_guide/data.json agree with the per-model result files.
"""
import base64
import csv
import json
import os
import re
import sys

REPO = sys.argv[1] if len(sys.argv) > 1 else "/home/user/shashikanth077/transformers-nlp"
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "frontend", "src", "labs", "lab3", "data")
PUBLIC = os.path.join(HERE, "..", "frontend", "public", "lab3")
RES = os.path.join(REPO, "code", "results")
os.makedirs(OUT, exist_ok=True)
os.makedirs(PUBLIC, exist_ok=True)

HEADER = ("// Generated by scripts/make_lab3_data.py from the team's public repository "
          "(github.com/shashikanth77/Transformers-NLP).\n// Do not edit by hand: re-run the script.\n")


def write(name, body):
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(HEADER + body)
    print(f"{name:18s} {os.path.getsize(path) / 1024:7.1f} KB")


def js(v):
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))


def read_csv(name):
    with open(os.path.join(RES, name), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


# ------------------------------------------------------------------ models (order of study_guide/data.json: pred string order)
MODELS = [
    ("tfidf_nb", "TF-IDF + Naive Bayes", "TF-IDF NB", "classical", "no", "TF-IDF + Naive Bayes"),
    ("tfidf_logreg", "TF-IDF + Logistic Regr.", "TF-IDF LR", "classical", "no", "TF-IDF + Logistic Regr."),
    ("tfidf_svm", "TF-IDF + Linear SVM", "TF-IDF SVM", "classical", "no", "TF-IDF + Linear SVM"),
    ("bilstm", "BiLSTM (from scratch)", "BiLSTM", "recurrent", "no", "BiLSTM (from scratch)"),
    ("ft_bert-tiny_8000", "BERT-tiny fine-tuned (8k)", "BERT-tiny", "transformer", "yes", "BERT-tiny fine-tuned (8k)"),
    ("ft_bert-small_8000", "BERT-small fine-tuned (8k)", "BERT-small", "transformer", "yes", "BERT-small fine-tuned (8k)"),
    ("ft_distilbert_8000", "DistilBERT fine-tuned (8k)", "DistilBERT-FT", "transformer", "yes", "DistilBERT fine-tuned (8k)"),
    ("pt_distilbert_sst2", "DistilBERT-SST2 (off-the-shelf)", "DistilBERT-SST2", "transformer", "yes", "DistilBERT-SST2 (off-the-shelf)"),
    ("pt_twitter_roberta", "Twitter-RoBERTa (off-the-shelf)", "Twitter-RoBERTa", "transformer", "yes", "Twitter-RoBERTa (off-the-shelf)"),
    ("zs_nli_distilroberta", "Zero-shot NLI DistilRoBERTa", "Zero-shot NLI", "transformer", "yes", "Zero-shot NLI DistilRoBERTa"),
]
RESULT = {t: json.load(open(os.path.join(RES, t + ".json"), encoding="utf-8")) for t, *_ in MODELS}
SUMMARY = {r["name"]: r for r in read_csv("summary_table.csv")}
STATS = {r["name"]: r for r in read_csv("statistics.csv")}
SUBSET = {r["name"]: r for r in read_csv("subset_accuracy.csv")}

models = []
for tag, name, short, fam, pre, csvname in MODELS:
    r, s = RESULT[tag], SUMMARY[csvname]
    assert abs(float(s["accuracy"]) - r["accuracy"]) < 1e-12, tag
    models.append({
        "tag": tag, "name": name, "short": short, "family": fam, "kind": r["family"], "pretrained": pre == "yes",
        "hub": r["model"], "trainSize": r["train_size"], "params": r["parameters"],
        "accuracy": float(s["accuracy"]), "precision": float(s["precision"]), "recall": float(s["recall"]),
        "f1": float(s["f1_macro"]), "trainSeconds": float(s["train_time_s"]), "latencyMs": float(s["latency_ms_per_sample"]),
        "confusion": r["confusion_matrix"],
        "epochs": r.get("epochs"), "lr": r.get("lr"),
        "devHistory": [h["dev_accuracy"] for h in r.get("history", [])],
    })

stats = {}
for tag, name, short, fam, pre, csvname in MODELS:
    s = STATS[csvname]
    stats[tag] = {"accuracy": float(s["accuracy"]), "ciLow": float(s["ci_low"]), "ciHigh": float(s["ci_high"]),
                  "bestOnly": int(s["b01_best_only"]), "modelOnly": int(s["b10_model_only"]), "p": float(s["mcnemar_p_vs_best"])}
subsets = {}
for tag, name, short, fam, pre, csvname in MODELS:
    s = SUBSET[csvname]
    subsets[tag] = {"all": float(s["all"]), "negation": float(s["negation"]), "contrast": float(s["contrast"])}

curve = {"bert-small": [], "tfidf-lr": []}
for r in read_csv("learning_curve.csv"):
    key = "bert-small" if r["series"].startswith("BERT") else "tfidf-lr"
    curve[key].append({"n": int(r["train_size"]), "accuracy": float(r["accuracy"]), "f1": float(r["f1_macro"])})
lc_time = []
for n in (500, 1000, 2000, 4000, 8000):
    j = json.load(open(os.path.join(RES, f"lc_bert-small_{n}.json"), encoding="utf-8"))
    assert j["train_size"] == n and abs(j["accuracy"] - [c for c in curve["bert-small"] if c["n"] == n][0]["accuracy"]) < 1e-12
    lc_time.append({"n": n, "trainSeconds": j["train_time_s"], "latencyMs": j["latency_ms_per_sample"]})

guide = json.load(open(os.path.join(REPO, "study_guide", "data.json"), encoding="utf-8"))
dataset = guide["dataset"]

# subset sizes (the keyword rules of 08_report.py) and the McNemar counts of the paper's headline pairs
neg_re = re.compile(r"\b(?:not|no|never|nothing|nor|neither)\b|n't")
con_re = re.compile(r"\b(?:but|although|though|yet|however)\b")
sent_texts = [x["s"] for x in guide["sentences"]]
subset_sizes = {"negation": sum(1 for t in sent_texts if neg_re.search(t)), "contrast": sum(1 for t in sent_texts if con_re.search(t))}
assert subset_sizes == {"negation": 184, "contrast": 130}, subset_sizes


def mcnemar_counts(a, b):
    """(sentences only A gets right, only B gets right) and the exact two-sided binomial p-value with p = 0.5."""
    from math import comb
    y = [x["y"] for x in guide["sentences"]]
    pa, pb = RESULT[a]["predictions"], RESULT[b]["predictions"]
    ra = sum(1 for i in range(len(y)) if pa[i] == y[i] and pb[i] != y[i])
    rb = sum(1 for i in range(len(y)) if pb[i] == y[i] and pa[i] != y[i])
    n, k = ra + rb, min(ra, rb)
    p = 1.0 if 2 * k >= n - 1 else min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n)
    return {"a": a, "b": b, "onlyA": ra, "onlyB": rb, "p": p}


pairs = [mcnemar_counts("ft_distilbert_8000", "tfidf_svm"), mcnemar_counts("ft_bert-small_8000", "tfidf_svm"),
         mcnemar_counts("bilstm", "tfidf_svm"), mcnemar_counts("zs_nli_distilroberta", "tfidf_logreg"),
         mcnemar_counts("ft_distilbert_8000", "pt_distilbert_sst2")]

write("expModels.ts", f"""
export type Family = "classical" | "recurrent" | "transformer";

/** One of the ten compared models: the columns of code/results/summary_table.csv plus confusion matrix and dev history. */
export interface ModelRec {{
  tag: string; name: string; short: string; family: Family;
  /** `family` field of the result JSON, e.g. "transformer-finetuned". */
  kind: string; pretrained: boolean; hub: string;
  trainSize: number; params: number;
  accuracy: number; precision: number; recall: number; f1: number;
  trainSeconds: number; latencyMs: number;
  /** [[TN, FP], [FN, TP]] as saved by the Python run. */
  confusion: [[number, number], [number, number]];
  epochs: number | null; lr: number | null; devHistory: number[];
}}

/** Order of the model list = order of the characters in the per-sentence prediction strings. */
export const MODELS: ModelRec[] = {js(models)};

/** statistics.csv: accuracy, bootstrap CI (numpy, seed 42, 2,000 resamples) and McNemar against the best model. */
export const STATS: Record<string, {{ accuracy: number; ciLow: number; ciHigh: number; bestOnly: number; modelOnly: number; p: number }}> = {js(stats)};

/** subset_accuracy.csv */
export const SUBSETS: Record<string, {{ all: number; negation: number; contrast: number }}> = {js(subsets)};

/** learning_curve.csv */
export const CURVE: Record<"bert-small" | "tfidf-lr", {{ n: number; accuracy: number; f1: number }}[]> = {js(curve)};

/** Sizes of the keyword-defined subsets of the 872 test sentences (the rules of 08_report.py). */
export const SUBSET_SIZES = {js(subset_sizes)};

/** Exact McNemar counts of the paper's headline pairs (computed from the predictions by this script). */
export const PAIRS: {{ a: string; b: string; onlyA: number; onlyB: number; p: number }}[] = {js(pairs)};

/** Fine-tuning time of BERT-small for each learning-curve size (results/lc_bert-small_N.json). */
export const LC_TIME: {{ n: number; trainSeconds: number; latencyMs: number }}[] = {js(lc_time)};

/** study_guide/data.json "dataset": train (65,349 rows) and test statistics. Dev numbers are in the paper's Table 3. */
export const DATASET = {js({k: dataset[k] for k in ("train", "dev", "test", "train_pos", "test_pos", "train_len", "test_len")})};
""")

# ------------------------------------------------------------------ the 872 sentences with all predictions
sents = guide["sentences"]
assert len(sents) == 872
preds = {}
for i, (tag, *_) in enumerate(MODELS):
    chars = "".join(x["p"][i] for x in sents)
    assert [int(c) for c in chars] == RESULT[tag]["predictions"], f"prediction mismatch for {tag}"
    preds[tag] = chars
gold = "".join(str(x["y"]) for x in sents)
# the gold labels must give the confusion matrices saved by the Python run (class 1 = positive)
for tag, *_ in MODELS:
    cm = RESULT[tag]["confusion_matrix"]
    tn = sum(1 for g, p in zip(gold, preds[tag]) if g == "0" and p == "0")
    tp = sum(1 for g, p in zip(gold, preds[tag]) if g == "1" and p == "1")
    assert cm[0][0] == tn and cm[1][1] == tp, tag
write("expPreds.ts", f"""
/** The 872 SST-2 test sentences (the official validation split), lower-cased and tokenised as in the dataset. */
export const SENTENCES: string[] = {js([x["s"] for x in sents])};

/** Gold labels, one character per sentence: 1 = positive, 0 = negative. */
export const GOLD = {js(gold)};

/** Predictions of every model (key = model tag), one character per sentence. Verified against code/results/<tag>.json. */
export const PREDS: Record<string, string> = {js(preds)};
""")

# ------------------------------------------------------------------ the real TF-IDF + logistic regression model
lr = guide["lr"]
terms = lr["terms"].split("\n")
assert len(terms) == lr["n_features"] == 73556
idf_b = base64.b64decode(lr["idf"])
coef_b = base64.b64decode(lr["coef"])
assert len(idf_b) == 2 * len(terms) and len(coef_b) == 2 * len(terms)
import struct
coef = struct.unpack(f"<{len(terms)}h", coef_b)
idf = struct.unpack(f"<{len(terms)}h", idf_b)
CH = 4
per = -(-len(terms) // CH)
for c in range(CH):
    a, b = c * per, min(len(terms), (c + 1) * per)
    body = (f"/** Chunk {c + 1} of {CH} of the real TF-IDF + logistic regression model (terms {a}..{b - 1}, alphabetical). "
            "idf and coef are int16 little-endian, base64, value = int / 1000. */\n"
            f"export const LR_CHUNK = {js({'terms': chr(10).join(terms[a:b]), 'idf': base64.b64encode(idf_b[2 * a:2 * b]).decode(), 'coef': base64.b64encode(coef_b[2 * a:2 * b]).decode()})};\n")
    write(f"expLr{c}.ts", body)
order = sorted(range(len(terms)), key=lambda i: -coef[i])
top = lambda idx: [{"t": terms[i], "w": coef[i] / 1000, "idf": idf[i] / 1000} for i in idx]
write("expLrTop.ts", f"""
export const LR_BIAS = {lr['bias']};
export const LR_FEATURES = {lr['n_features']};
export const LR_CHUNKS = {CH};
/** Agreement of the quantised browser model with the scikit-learn model on the 872 test sentences (from study_guide/export_data.py). */
export const LR_AGREEMENT = {lr['agreement']};
/** The 30 most positive and the 30 most negative n-gram weights of the real model (coef, idf). */
export const LR_TOP_POS: {{ t: string; w: number; idf: number }}[] = {js(top(order[:30]))};
export const LR_TOP_NEG: {{ t: string; w: number; idf: number }}[] = {js(top(order[::-1][:30]))};
""")

# ------------------------------------------------------------------ the code of the nine scripts
FILES = [
    ("01_prepare_data.py", "py"), ("02_classical_baselines.py", "py"), ("03_bilstm.py", "py"),
    ("04_finetune_transformer.py", "py"), ("05_pretrained_transformers.py", "py"),
    ("06_learning_curve_classical.py", "py"), ("07_attention_visualisation.py", "py"),
    ("08_report.py", "py"), ("09_diagrams.py", "py"), ("utils.py", "py"), ("run_all.sh", "sh"), ("requirements.txt", "txt"),
]
code = []
for name, lang in FILES:
    text = open(os.path.join(REPO, "code", name), encoding="utf-8").read().replace("\r\n", "\n").rstrip("\n")
    code.append({"file": name, "lang": lang, "lines": text.count("\n") + 1, "code": text})
write("expCode.ts", f"""
export interface CodeFile {{ file: string; lang: string; lines: number; code: string }}
/** The real files of code/ in the repository, byte for byte (line endings normalised to LF). */
export const CODE_FILES: CodeFile[] = {js(code)};
""")

# ------------------------------------------------------------------ Fig. 7 (attention heat-map), re-quantised to a small PNG
src = os.path.join(REPO, "code", "figures", "attention_heatmap.png")
dst = os.path.join(PUBLIC, "attention-fig7.png")
try:
    from PIL import Image
    im = Image.open(src).convert("RGB")
    im.quantize(colors=128, method=Image.Quantize.MEDIANCUT).save(dst, optimize=True)
except ImportError:
    import shutil
    shutil.copyfile(src, dst)
print("attention-fig7.png", round(os.path.getsize(dst) / 1024, 1), "KB")
